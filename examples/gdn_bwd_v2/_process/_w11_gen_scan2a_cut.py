#   cut=2: A(replay)+B(Kt/beK/W)          -- 跳过 C..F
#   cut=3: A+B+QK^T gemm + L0C->GM       -- 跳过 Gamma/pk2 段与 E/F
#   cut=4: A+B+C+D  (QK^T..P + accum init) -- 跳过 E/F
