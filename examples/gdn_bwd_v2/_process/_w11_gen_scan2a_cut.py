OUT = "/Users/pengweiye/Documents/codes/tilelang-ascend/examples/gdn_bwd_v2/_process/_w11_scan2a_cut.py"

lines = open(SRC).read().split("\n")

def_line = next(i for i, ln in enumerate(lines) if ln.startswith("def gdn_bwd_v2_scan2a("))
jit_line = next(i for i in range(def_line - 1, def_line - 5, -1) if lines[i].startswith("@tilelang.jit("))
ret = next(i for i in range(def_line, len(lines)) if lines[i] == "    return main")
c_mark = next(i for i in range(def_line, ret) if lines[i].strip().startswith("# ---- raw QK^T"))
c2_mark = next(i for i in range(c_mark, ret) if lines[i].strip().startswith("# Gamma (aux lane"))
e_mark = next(i for i in range(c2_mark, ret) if lines[i].strip().startswith("for bv in T.serial(bv_num):"))
f_mark = next(i for i in range(def_line, ret) if lines[i].strip().startswith("# ---- dW -> WS_DW boundary"))

body = lines[jit_line:ret + 1]
c_local = c_mark - jit_line
c2_local = c2_mark - jit_line
e_local = e_mark - jit_line
f_local = f_mark - jit_line

new_fn = (
    body[:c_local]
    + ["                if cut >= 3:"]
    + [("    " + ln) if ln.strip() else ln for ln in body[c_local:c2_local]]
    + ["                if cut >= 4:"]
    + [("    " + ln) if ln.strip() else ln for ln in body[c2_local:e_local]]
    + ["                if cut >= 5:"]
    + [("    " + ln) if ln.strip() else ln for ln in body[e_local:f_local]]
    + ["                if cut >= 6:"]
    + [("    " + ln) if ln.strip() else ln for ln in body[f_local:-1]]
    + body[-1:]
)
fn_text = "\n".join(new_fn)
fn_text = fn_text.replace("def gdn_bwd_v2_scan2a(", "def scan2a_cut(", 1)
assert fn_text.count("    return main") == 1
fn_text = fn_text.replace("BV, BK, dtype=\"float16\"", "BV, BK, cut, dtype=\"float16\"", 1)

