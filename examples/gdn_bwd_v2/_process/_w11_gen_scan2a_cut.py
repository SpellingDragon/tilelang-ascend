    from gdn_bwd_v2 import gdn_bwd_v2_cumsum, gdn_bwd_v2_scan1, gdn_bwd_v2_solve_a

    cut = int(sys.argv[1])
    B, H, T_len, DK, DV = 1, 1, 64, 64, 64
    C, BV, BK = 64, 64, 64
    dt = torch.float16
